"""Media storage helpers (Stage 1, Checkpoint 4).

Media files are saved under backend/data/media/. Filenames are generated by
the app itself ({source_id}_{telegram_message_id}.{ext}), but safe_media_path
still guards against path traversal for any caller-supplied name/id.
"""
import re
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
MEDIA_DIR = BACKEND_DIR / "data" / "media"

MAX_UPLOAD_MB = 50

ALLOWED_MEDIA_MIME_PREFIXES: tuple[str, ...] = (
    "image/",
    "video/",
    "audio/",
    "application/pdf",
    "text/",
    "application/zip",
    "application/octet-stream",
)

_SAFE_NAME_RE = re.compile(r"[^A-Za-z0-9._-]")


def is_allowed_mime(mime: str | None) -> bool:
    if not mime:
        return False
    return any(mime.startswith(prefix) for prefix in ALLOWED_MEDIA_MIME_PREFIXES)


def safe_media_path(name: str) -> Path:
    """Return a path inside MEDIA_DIR for the given file name.

    Strips directory components and disallowed characters so the result can
    never escape MEDIA_DIR (path traversal protection), then resolves and
    re-checks containment as a second guard.
    """
    MEDIA_DIR.mkdir(parents=True, exist_ok=True)

    candidate = Path(name).name  # drop any directory components (../, /)
    candidate = _SAFE_NAME_RE.sub("_", candidate).lstrip(".")
    if not candidate:
        candidate = "file"

    resolved = (MEDIA_DIR / candidate).resolve()
    if MEDIA_DIR.resolve() not in resolved.parents and resolved != MEDIA_DIR.resolve():
        raise ValueError("Noto‘g‘ri media fayl nomi (path traversal).")
    return resolved


TMP_MEDIA_DIR = MEDIA_DIR / "tmp"


def safe_tmp_media_path(name: str) -> Path:
    """Like safe_media_path, but inside MEDIA_DIR/tmp/ for outgoing-reply uploads."""
    TMP_MEDIA_DIR.mkdir(parents=True, exist_ok=True)

    candidate = Path(name).name
    candidate = _SAFE_NAME_RE.sub("_", candidate).lstrip(".")
    if not candidate:
        candidate = "file"

    resolved = (TMP_MEDIA_DIR / candidate).resolve()
    if TMP_MEDIA_DIR.resolve() not in resolved.parents and resolved != TMP_MEDIA_DIR.resolve():
        raise ValueError("Noto‘g‘ri media fayl nomi (path traversal).")
    return resolved
